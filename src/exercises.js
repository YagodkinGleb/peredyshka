/* Выбор уровня по длительности перерыва в минутах */
function tierForRest(restMin){
  if(restMin <= 2) return 'micro';
  if(restMin <= 6) return 'short';
  return 'long';
}

/*
 * Ротация. Помним последние выпавшие упражнения и зоны,
 * чтобы не повторяться и не бить одну группу мышц подряд.
 */
function createPicker(){
  let recentNames = [];
  let recentZones = [];

  return function pick(restMin){
    const tier = tierForRest(restMin);
    const pool = EXERCISES[tier];

    const nameMemory = Math.min(6, Math.floor(pool.length / 2));
    const zoneMemory = 2;

    // сначала пробуем исключить и недавние названия, и недавние зоны
    let candidates = pool.filter(function(e){
      return recentNames.indexOf(e.name) === -1 && recentZones.indexOf(e.zone) === -1;
    });

    // если слишком строго — ослабляем требование по зоне
    if(candidates.length === 0){
      candidates = pool.filter(function(e){ return recentNames.indexOf(e.name) === -1; });
    }
    // на совсем маленьком пуле берём что угодно
    if(candidates.length === 0){
      candidates = pool.slice();
    }

    const chosen = candidates[Math.floor(Math.random() * candidates.length)];

    recentNames.push(chosen.name);
    while(recentNames.length > nameMemory) recentNames.shift();
    recentZones.push(chosen.zone);
    while(recentZones.length > zoneMemory) recentZones.shift();

    return Object.assign({ tier: tier }, chosen);
  };
}

